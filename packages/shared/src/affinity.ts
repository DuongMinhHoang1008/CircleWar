export function affinityDescription(id: string, multiplier = 1) {
  return (
    "+8% hiệu lực chỉ số và hiệu ứng. " +
    (ITEM_AFFINITY[id]?.text || "").replace(/\{(\d+)\}/g, (_, n: string) =>
      String(Math.max(1, Math.round(Number(n) * multiplier))),
    )
  );
}
