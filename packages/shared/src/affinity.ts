/** Bounded identity effects in addition to the existing +8% item multiplier. */
export type AffinityTrigger = "start" | "hit4" | "skill" | "super" | "low";
export interface AffinityEffect {
  trigger: AffinityTrigger;
  cooldown: number;
  maxUses: number;
  kind:
    | "shield"
    | "heal"
    | "allyShield"
    | "allyHeal"
    | "energy"
    | "bonus"
    | "speed"
    | "cleanse"
    | "slow"
    | "burn";
  value: number;
  ticks: number;
  text: string;
}
